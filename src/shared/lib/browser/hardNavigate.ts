/**
 * Полная перезагрузка на другой адрес. Нужна, когда надо сбросить всё клиентское состояние
 * (выход, истёкшая сессия) или уйти на чужой домен (страница OAuth-провайдера).
 * Вынесена отдельно, чтобы её можно было подменить в тестах.
 */
export function hardNavigate(url: string) {
  window.location.assign(url);
}
